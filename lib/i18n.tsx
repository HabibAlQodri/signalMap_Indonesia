type TranslationContextValue = {
  locale: AppLocale;
  t: (message: string, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<TranslationContextValue>({
  locale: "id",
  t: (message) => message,
});

function detectLocale(): AppLocale {
  const preferredLanguages = navigator.languages.length ? navigator.languages : [navigator.language];
  for (const language of preferredLanguages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("en")) return "en";
    if (normalized.startsWith("id")) return "id";
  }
  return "id";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const locale = useSyncExternalStore<AppLocale>(
    (callback) => {
      window.addEventListener("languagechange", callback);
      return () => window.removeEventListener("languagechange", callback);
    },
    detectLocale,
    () => "id",
  );

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = locale === "en"
      ? english["SinyalNusa | Tren Performa Jaringan Ookla"]
      : "SinyalNusa | Tren Performa Jaringan Ookla";
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) {
      description.content = locale === "en"
        ? english["Peta dan analisis historis performa mobile dan fixed broadband Ookla di Indonesia dan sekitarnya."]
        : "Peta dan analisis historis performa mobile dan fixed broadband Ookla di Indonesia dan sekitarnya.";
    }
  }, [locale]);

  const value = useMemo<TranslationContextValue>(() => ({
    locale,
    t: (message, values) => {
      let translated = locale === "en" ? english[message] ?? message : message;
      if (values) {
        for (const [key, replacement] of Object.entries(values)) {
          translated = translated.replaceAll(`{${key}}`, String(replacement));
        }
      }
      return translated;
    },
  }), [locale]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
